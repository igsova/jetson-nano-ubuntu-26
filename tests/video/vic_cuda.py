class GStreamer:
    def __init__(self):
        self.lib = ctypes.CDLL('libgstreamer-1.0.so.0')
        self.app = ctypes.CDLL('libgstapp-1.0.so.0')
        for name, restype, args in [
                ('gst_init', None, [P, P]),
                ('gst_parse_launch', P, [c_char_p, POINTER(P)]),
                ('gst_bin_get_by_name', P, [P, c_char_p]),
                ('gst_element_set_state', c_int, [P, c_int]),
                ('gst_element_get_bus', P, [P]),
                ('gst_bus_timed_pop_filtered', P, [P, c_u64, c_int]),
                ('gst_message_parse_error', None, [P, POINTER(P), POINTER(c_char_p)]),
                ('gst_sample_get_buffer', P, [P]),
                ('gst_buffer_map', c_int, [P, POINTER(MapInfo), c_int]),
                ('gst_buffer_unmap', None, [P, POINTER(MapInfo)]),
                ('gst_mini_object_unref', None, [P]),
                ('gst_object_unref', None, [P])]:
            fn = getattr(self.lib, name)
            fn.restype, fn.argtypes = restype, args
        self.app.gst_app_sink_try_pull_sample.restype = P
        self.app.gst_app_sink_try_pull_sample.argtypes = [P, c_u64]
        self.lib.gst_init(None, None)

    def error(self, pipeline):
        """The pipeline's first error message, if it has one."""
        bus = self.lib.gst_element_get_bus(pipeline)
        message = self.lib.gst_bus_timed_pop_filtered(bus, 0, MESSAGE_ERROR)
        self.lib.gst_object_unref(bus)
        if not message:
            return None
        error, debug = P(), c_char_p()
        self.lib.gst_message_parse_error(message, ctypes.byref(error), ctypes.byref(debug))
        text = ctypes.cast(error, POINTER(GError)).contents.message.decode(errors='replace')
        self.lib.gst_mini_object_unref(message)
        return f"{text} ({(debug.value or b'').decode(errors='replace')[:200]})"

    def pull(self, sink, into, size):
        """The next frame from SINK, copied into INTO; False at the end of the stream or on a timeout."""
        sample = self.app.gst_app_sink_try_pull_sample(sink, PULL_SECONDS * SECOND)
        if not sample:
            return False
        try:
            info = MapInfo()
            buffer = self.lib.gst_sample_get_buffer(sample)
            if not buffer or not self.lib.gst_buffer_map(buffer, ctypes.byref(info), MAP_READ):
                raise Failed('a frame could not be mapped')
            try:
                if info.size != size:
                    raise Failed(f'a frame of {info.size} bytes, not {size}')
                ctypes.memmove(into, info.data, size)
            finally:
                self.lib.gst_buffer_unmap(buffer, ctypes.byref(info))
        finally:
            self.lib.gst_mini_object_unref(sample)
        return True


def cpu_row(i420, rgba, y, down):
    """row_sse.c's sums for row Y, in Python."""
    half, cy = WIDTH // 2, chroma_row(y, down)
    luma = i420[y * WIDTH:(y + 1) * WIDTH]
    u = i420[WIDTH * HEIGHT + cy * half:][:half]
    v = i420[WIDTH * HEIGHT + half * (HEIGHT // 2) + cy * half:][:half]
    out = rgba[y * WIDTH * 4:(y + 1) * WIDTH * 4]
    r = g = b = 0
    for x in range(EDGE, WIDTH - EDGE):
        c = (x + MOVE) // 2
        lum = K_Y * (luma[x] - 16) + 32768
        cu, cv = u[c] - 128, v[c] - 128
        d = min(255, max(0, (lum + K_RV * cv) >> 16)) - out[4 * x]
        r += d * d
        d = min(255, max(0, (lum + K_GU * cu + K_GV * cv) >> 16)) - out[4 * x + 1]
        g += d * d
        d = min(255, max(0, (lum + K_BU * cu) >> 16)) - out[4 * x + 2]
        b += d * d
    return r, g, b


def chroma_row(y, down):
    """The input's chroma row for row Y, as row_sse.c takes it."""
    return min((y + down) // 2, HEIGHT // 2 - 1)


def model_row(i420, y, down):
    """row_sse.c's model of row Y: (Y, U, V) and the predicted (R, G, B) for each compared column."""
    half, cy = WIDTH // 2, chroma_row(y, down)
    u0, v0 = WIDTH * HEIGHT + cy * half, WIDTH * HEIGHT + half * (HEIGHT // 2) + cy * half
    row = []
    for x in range(EDGE, WIDTH - EDGE):
        c = (x + MOVE) // 2
        luma, cu, cv = i420[y * WIDTH + x], i420[u0 + c], i420[v0 + c]
        lum = K_Y * (luma - 16) + 32768
        row.append(((luma, cu, cv), (min(255, max(0, (lum + K_RV * (cv - 128)) >> 16)),
                                     min(255, max(0, (lum + K_GU * (cu - 128) + K_GV * (cv - 128)) >> 16)),
                                     min(255, max(0, (lum + K_BU * (cu - 128)) >> 16)))))
    return row


def row_detail(i420, rgba, y, down):
    """Output row Y against the model: the columns a channel misses by 16 or more, the worst pixel,
    and which input row's model within four rows it fits best (a row moved up or down shows there)."""
    out = [rgba[4 * (y * WIDTH + x):4 * (y * WIDTH + x) + 4] for x in range(EDGE, WIDTH - EDGE)]
    big, worst = [], (-1, None)
    for x, ((yuv, model), pixel) in enumerate(zip(model_row(i420, y, down), out), EDGE):
        miss = max(abs(m - o) for m, o in zip(model, pixel))
        if miss >= 16:
            big.append(x)
        if miss > worst[0]:
            worst = (miss, f"x={x} yuv={','.join(map(str, yuv))} model={','.join(map(str, model))} "
                           f"out={','.join(map(str, pixel))}")
    fits = []
    for r in range(max(0, y - 4), min(HEIGHT, y + 5)):
        sse = sum((m - o) ** 2 for (_, model), pixel in zip(model_row(i420, r, down), out)
                  for m, o in zip(model, pixel))
        fits.append((psnr(sse, 3 * len(out)), r))
    best = max(fits, key=lambda f: (f[0], -abs(f[1] - y)))
    return big, worst[1], f'{best[1]}:{shown(best[0])}'


def spans(values, limit=6):
    """Sorted integers as merged ranges, the first LIMIT of them."""
    runs = []
    for v in sorted(values):
        if runs and v == runs[-1][1] + 1:
            runs[-1][1] = v
        else:
            runs.append([v, v])
    text = ','.join(f'{a}' if a == b else f'{a}-{b}' for a, b in runs[:limit])
    return text + (f',+{len(runs) - limit} more' if len(runs) > limit else '')


def psnr(sse, count):
    return math.inf if sse == 0 else 10 * math.log10(255 ** 2 * count / sse)


def shown(db):
    return 'inf' if db == math.inf else f'{db:.1f}'


def mapped():
    """The NVIDIA libraries (and vic_patch.so) this process has mapped."""
    paths = set()
    with open('/proc/self/maps') as maps:
        for line in maps:
            fields = line.split(None, 5)
            path = fields[5].strip() if len(fields) == 6 else ''
            if path.startswith('/') and NV_LIB.match(os.path.basename(path)):
                paths.add(path)
    return sorted(paths)


def run(args):
    count = (HEIGHT - 2 * EDGE) * (WIDTH - 2 * EDGE)
    say('VIC_CUDA_FRAMES', f'{args.frames} size={WIDTH}x{HEIGHT} min_db={args.min_db:g} context={args.context} '
        f'chroma_down={args.chroma_down}')
    cu = Driver()
    cu('CUDA_INIT', 'cuInit', 0)
    version, dev, major, minor = c_int(), c_int(), c_int(), c_int()
    cu('DRIVER_VERSION', 'cuDriverGetVersion', ctypes.byref(version))
    cu('DEVICE', 'cuDeviceGet', ctypes.byref(dev), 0)
    name = ctypes.create_string_buffer(256)
    cu('DEVICE_NAME', 'cuDeviceGetName', name, len(name), dev)
    cu('DEVICE_COMPUTE', 'cuDeviceGetAttribute', ctypes.byref(major), COMPUTE_MAJOR, dev)
    cu('DEVICE_COMPUTE', 'cuDeviceGetAttribute', ctypes.byref(minor), COMPUTE_MINOR, dev)
    say('CUDA', f'PASS driver={version.value} device={name.value.decode(errors="replace")!r} '
        f'compute={major.value}.{minor.value}')
    context, kernel = Context(cu, args.context, dev), None
    if args.context != 'late':  # CUDA first, before the converter starts
        context.make()
        kernel = Kernel(cu, context, args.chroma_down)
    i420 = (ctypes.c_ubyte * I420_SIZE)()
    rgba = (ctypes.c_ubyte * RGBA_SIZE)()
    sums = (c_u64 * (HEIGHT * 3))()

    gst = GStreamer()
    text = PIPELINE.format(frames=args.frames)
    say('PIPELINE', text)
    error = P()
    pipeline = gst.lib.gst_parse_launch(text.encode(), ctypes.byref(error))
    if error.value:
        message = ctypes.cast(error, POINTER(GError)).contents.message.decode(errors='replace')
        say('PIPELINE', f'FAIL {message}')
        raise Failed('PIPELINE')
    sink_in = gst.lib.gst_bin_get_by_name(pipeline, b'frames_in')
    sink_out = gst.lib.gst_bin_get_by_name(pipeline, b'frames_out')
    if gst.lib.gst_element_set_state(pipeline, STATE_PLAYING) == STATE_CHANGE_FAILURE:
        say('PIPELINE', f'FAIL could not start: {gst.error(pipeline)}')
        raise Failed('PIPELINE')
    ok, worst, frames, checked, low_seen = context.state('started'), math.inf, 0, 0, {}
    failure, began = None, time.monotonic()
    try:
        for n in range(args.frames):
            if not gst.pull(sink_in, i420, I420_SIZE) or not gst.pull(sink_out, rgba, RGBA_SIZE):
                problem = gst.error(pipeline) or f'no frame within {PULL_SECONDS} s, or the stream ended early'
                say('FRAMES', f'FAIL at frame {n}: {problem}')
                raise Failed('FRAMES')
            frames += 1
            if n == 0:
                if kernel is None:  # late
                    context.make()
                    kernel = Kernel(cu, context, args.chroma_down)
                ok &= context.state('first_frames')
            gpu_ms = kernel.sums(i420, rgba, sums)
            # The CPU repeats some rows; the rows not compared must hold 0.
            first = EDGE + (n * 7) % CPU_ROW_STEP
            rows = range(first, HEIGHT - EDGE, CPU_ROW_STEP)
            in_bytes, out_bytes = bytes(i420), bytes(rgba)
            wrong = [y for y in rows
                     if cpu_row(in_bytes, out_bytes, y, args.chroma_down) != tuple(sums[3 * y:3 * y + 3])]
            wrong += [y for y in (*range(EDGE), *range(HEIGHT - EDGE, HEIGHT)) if any(sums[3 * y:3 * y + 3])]
            db = [psnr(sum(sums[c::3]), count) for c in range(3)]
            worst, checked = min(worst, *db), checked + 1
            row_db = {y: min(psnr(v, WIDTH - 2 * EDGE) for v in sums[3 * y:3 * y + 3])
                      for y in range(EDGE, HEIGHT - EDGE)}
            low = [y for y, v in row_db.items() if v < args.min_db]
            good = not wrong and min(db) >= args.min_db
            ok &= good
            print(f"FRAME n={n} R={shown(db[0])} G={shown(db[1])} B={shown(db[2])} worst={shown(min(db))} "
                  f"cpu_rows={len(rows)} cpu={'MATCH' if not wrong else 'DIFFER rows=' + ','.join(map(str, wrong))} "
                  f"low_rows={len(low)}{':' + spans(low) if low else ''} gpu_ms={gpu_ms:.1f} "
                  f"{'PASS' if good else 'FAIL'}", flush=True)
            if low and not low_seen:
                y = min(low, key=row_db.get)
                big, pixel, best = row_detail(in_bytes, out_bytes, y, args.chroma_down)
                near = ' '.join(f'{r}:{shown(row_db[r])}' for r in range(y - 2, y + 3) if r in row_db)
                print(f'ROW_DETAIL frame={n} y={y} db={shown(row_db[y])} '
                      f"big_columns={len(big)}{':' + spans(big) if big else ''} worst {pixel} "
                      f'best_input_row={best} rows {near}', flush=True)
            for y in low:
                low_seen[y] = low_seen.get(y, 0) + 1
        if gst.pull(sink_out, rgba, RGBA_SIZE):
            say('FRAMES', f'FAIL more than {args.frames} frames')
            ok = False
        problem = gst.error(pipeline)
        if problem:
            say('PIPELINE_ERROR', problem)
            ok = False
    except Failed as stopped:  # the lines below still go out
        failure = str(stopped)
    finally:
        gst.lib.gst_element_set_state(pipeline, STATE_NULL)
        for element in (sink_in, sink_out, pipeline):
            if element:
                gst.lib.gst_object_unref(element)
    say('FRAMES_RECEIVED', f'{frames} seconds={time.monotonic() - began:.1f}')
    if low_seen:
        print(f'LOW_ROWS rows={len(low_seen)}:{spans(low_seen, 12)} in_every_frame='
              f'{sum(1 for v in low_seen.values() if v == checked)} (below {args.min_db:g} dB)', flush=True)
    ok &= context.state('stopped')

    # The VIC fix's own count, when vic_patch.so is in the process.
    counts = (c_uint * 5)()
    try:
        groups = ctypes.CDLL(None).vic_patch_counts
    except AttributeError:
        groups = None
    if groups is None:
        say('VIC_PATCH', 'absent (no vic_patch.so in this process)')
        if os.environ.get('VIC_PATCH'):
            say('VIC_PATCH_CHECK', 'FAIL VIC_PATCH is set but vic_patch.so is not loaded')
            ok = False
    else:
        groups.restype, groups.argtypes = c_uint, [POINTER(c_uint)]
        bits = groups(counts)
        seen, patched, unchanged, skipped, failed = counts
        print(f'VIC_PATCH groups=0x{bits:x} jobs={seen} patched={patched} unchanged={unchanged} '
              f'skipped={skipped} failed={failed}', flush=True)
        if os.environ.get('VIC_PATCH') and (not bits or not patched or failed):
            say('VIC_PATCH_CHECK', f"FAIL VIC_PATCH={os.environ['VIC_PATCH']} should patch jobs, none failing")
            ok = False
    libs = mapped()
    for path in libs:
        print(f'LIB {path}', flush=True)
    cuda = {os.path.realpath(p) for p in libs if os.path.basename(p).startswith('libcuda.so')}
    if len(cuda) != 1:
        say('LIB_CUDA', f"FAIL {len(cuda)} libcuda files mapped: {' '.join(sorted(cuda)) or 'none'}")
        ok = False
    else:
        say('LIB_CUDA', f'PASS {cuda.pop()}')
    if not any(os.path.basename(p) == 'libgstnvvidconv.so' for p in libs):
        say('LIB_CONVERTER', 'FAIL libgstnvvidconv.so is not mapped in this process')
        ok = False

    try:
        if kernel:
            kernel.free()
        context.end()
    except Failed as stopped:
        failure = failure or str(stopped)
    ok &= failure is None and frames == args.frames
    say('VIC_CUDA', f"{'PASS' if ok else 'FAIL'}{' ' + failure if failure else ''} frames={frames} "
        f"worst_db={shown(worst) if checked else '-'} (needs {args.min_db:g} per channel, context={args.context})")
    return 0 if ok else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--frames', type=int, default=30)
    parser.add_argument('--min-db', type=float, default=40)
    parser.add_argument('--context', choices=('primary', 'own', 'pushed', 'late'), default='primary')
    parser.add_argument('--chroma-down', type=int, choices=(0, 1), default=0)
    args = parser.parse_args()
    if args.frames < 1:
        parser.error('--frames must be at least 1')
    try:
        return run(args)
    except Failed as failure:
        say('VIC_CUDA', f'FAIL {failure}')
        return 1


if __name__ == '__main__':
    sys.exit(main())
