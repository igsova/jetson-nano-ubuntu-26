class Failed(Exception):
    pass


def say(key, value):
    print(f'{key}={value}', flush=True)


class Driver:
    def __init__(self):
        self.lib = ctypes.CDLL('libcuda.so.1')
        for name, args in DRIVER_API.items():
            fn = getattr(self.lib, name)
            fn.restype, fn.argtypes = c_int, args

    def __call__(self, step, name, *args):
        rc = getattr(self.lib, name)(*args)
        if rc:
            say(step, f'FAIL {name} {rc} {self.name(rc)}')
            raise Failed(step)

    def name(self, rc):
        text = c_char_p()
        return text.value.decode() if self.lib.cuGetErrorName(rc, ctypes.byref(text)) == 0 and text.value \
            else 'unknown'


class Context:
    """The CUDA context the checks run in, as --context picks it (see the top)."""

    def __init__(self, cu, mode, dev):
        self.cu, self.mode, self.dev, self.ctx = cu, mode, dev, P()

    def make(self):
        if self.mode == 'primary':
            self.cu('CONTEXT', 'cuDevicePrimaryCtxRetain', ctypes.byref(self.ctx), self.dev)
            self.cu('CONTEXT', 'cuCtxSetCurrent', self.ctx)
        else:
            self.cu('CONTEXT', 'cuCtxCreate_v2', ctypes.byref(self.ctx), 0, self.dev)
            if self.mode == 'pushed':
                self.cu('CONTEXT', 'cuCtxPopCurrent_v2', ctypes.byref(P()))
        say('CONTEXT', f'{self.mode} made')

    def __enter__(self):  # pushed: current only within
        if self.mode == 'pushed':
            self.cu('CONTEXT_PUSH', 'cuCtxPushCurrent_v2', self.ctx)
        return self

    def __exit__(self, kind, value, trace):
        if self.mode == 'pushed':
            if kind is None:
                self.cu('CONTEXT_POP', 'cuCtxPopCurrent_v2', ctypes.byref(P()))
            else:
                self.cu.lib.cuCtxPopCurrent_v2(ctypes.byref(P()))

    def state(self, where):
        """A CONTEXT_STATE line at WHERE: the context current on this thread (ours, the primary
        context, another or none) and whether it works, and whether ours works."""
        if not self.ctx.value:
            say('CONTEXT_STATE', f'{where} not made yet')
            return True
        cu, current = self.cu, P()
        rc = cu.lib.cuCtxGetCurrent(ctypes.byref(current))
        if rc:
            say('CONTEXT_STATE', f'{where} FAIL cuCtxGetCurrent {cu.name(rc)}')
            return False
        relation, theirs = 'none' if not current.value else 'ours' if current.value == self.ctx.value else 'other', ''
        if relation == 'other':
            theirs = f' current_works={cu.name(cu.lib.cuCtxSynchronize())}'
            flags, active, primary = c_uint(), c_int(), P()
            if cu.lib.cuDevicePrimaryCtxGetState(self.dev, ctypes.byref(flags), ctypes.byref(active)) == 0 \
                    and active.value and cu.lib.cuDevicePrimaryCtxRetain(ctypes.byref(primary), self.dev) == 0:
                relation = 'primary' if primary.value == current.value else relation
                cu.lib.cuDevicePrimaryCtxRelease_v2(self.dev)
        if self.mode == 'pushed':  # ours on top of whatever is current, then off again
            rc = cu.lib.cuCtxPushCurrent_v2(self.ctx)
            ours = cu.name(rc if rc else cu.lib.cuCtxSynchronize())
            if not rc:
                cu.lib.cuCtxPopCurrent_v2(ctypes.byref(P()))
        else:
            ours = cu.name(cu.lib.cuCtxSynchronize()) if relation == 'ours' else 'not current'
        good = ours == 'CUDA_SUCCESS'
        say('CONTEXT_STATE', f"{where} current={relation}{theirs} ours={ours} {'PASS' if good else 'FAIL'}")
        return good

    def end(self):
        if not self.ctx.value:
            return
        if self.mode == 'primary':
            self.cu('CONTEXT_END', 'cuCtxSetCurrent', None)
            self.cu('CONTEXT_END', 'cuDevicePrimaryCtxRelease_v2', self.dev)
        else:
            self.cu('CONTEXT_END', 'cuCtxDestroy_v2', self.ctx)


class Kernel:
    """row_sse JIT-compiled in CONTEXT, with its device memory."""

    def __init__(self, cu, context, down):
        self.cu, self.context, self.module, self.function, self.device = cu, context, P(), P(), {}
        with context:
            log = ctypes.create_string_buffer(8192)
            options = (c_int * 2)(JIT_ERROR_LOG, JIT_ERROR_SIZE)
            values = (P * 2)(ctypes.cast(log, P), P(len(log)))
            rc = cu.lib.cuModuleLoadDataEx(ctypes.byref(self.module), PTX, 2, options, values)
            if rc:
                for line in log.value.decode(errors='replace').splitlines():
                    say('JIT_ERROR', line)
                say('MODULE', f'FAIL cuModuleLoadDataEx {rc} {cu.name(rc)}')
                raise Failed('MODULE')
            cu('MODULE', 'cuModuleGetFunction', ctypes.byref(self.function), self.module, b'row_sse')
            say('MODULE', 'PASS row_sse JIT-compiled from PTX')
            for key, size in (('i420', I420_SIZE), ('rgba', RGBA_SIZE), ('sse', HEIGHT * 3 * 8)):
                pointer = c_u64()
                cu('ALLOC', 'cuMemAlloc_v2', ctypes.byref(pointer), size)
                self.device[key] = pointer.value
        self.values = [c_u64(self.device['i420']), c_u64(self.device['rgba']), c_int(WIDTH), c_int(HEIGHT),
                       c_int(down), c_u64(self.device['sse'])]
        self.params = (P * len(self.values))(*[ctypes.cast(ctypes.byref(v), P) for v in self.values])

    def sums(self, i420, rgba, into):
        """Each row's sums for one frame pair, into INTO; the milliseconds it took."""
        cu, started = self.cu, time.monotonic()
        with self.context:
            cu('COPY_IN', 'cuMemcpyHtoD_v2', self.device['i420'], i420, I420_SIZE)
            cu('COPY_IN', 'cuMemcpyHtoD_v2', self.device['rgba'], rgba, RGBA_SIZE)
            cu('LAUNCH', 'cuLaunchKernel', self.function, (HEIGHT + BLOCK - 1) // BLOCK, 1, 1, BLOCK, 1, 1, 0,
               None, self.params, None)
            cu('SYNC', 'cuCtxSynchronize')
            cu('COPY_OUT', 'cuMemcpyDtoH_v2', into, self.device['sse'], HEIGHT * 3 * 8)
        return (time.monotonic() - started) * 1000

    def free(self):
        with self.context:
            for pointer in self.device.values():
                self.cu('FREE', 'cuMemFree_v2', pointer)
            self.cu('UNLOAD', 'cuModuleUnload', self.module)


