#!/usr/bin/env python3
"""Convert pictures on VIC and check them with CUDA, in one program.

Usage: nano-r35-video python3 -I vic_cuda.py [--frames N] [--min-db DB]
           [--context primary|own|pushed|late] [--chroma-down 0|1]

Run through nano-l4t-r35-video's launcher, this process loads JetPack 5's
video converter (nvvidconv, through GStreamer) with the VIC fix and CUDA
11.4's driver library (the installed nano-l4t-cuda) together. It makes a CUDA
context and JIT-compiles the kernel below, then starts one GStreamer pipeline:
N frames of a moving 1280x720 I420 (BT.601) test pattern, each kept as it is
and also converted by nvvidconv on VIC into RGBA in NVMM buffers and back to
system memory. Each frame pair is copied to the GPU, where the kernel
(row_sse.c) sums each channel's squared error of VIC's RGBA against
limited-range BT.601 with VIC's chroma placement, row by row. The CPU repeats
the sum for 16 rows of each frame and must get the same numbers, which shows
the kernel ran as written. Every channel of every frame must reach MIN_DB
(default 40, as the probe's VIC check). The probe's colour check samples
every eighth row; this one compares every row, and each FRAME line gives the
rows below MIN_DB (low_rows). For the first frame with such rows, a
ROW_DETAIL line gives the worst row's columns 16 or more off in a channel,
its worst pixel, and the input row within four whose model it fits best;
LOW_ROWS at the end gathers every frame's. --chroma-down 1 has odd rows take
the next row pair's chroma (row_sse.c's DOWN), as VIC does for JetPack 5's
converter without the fix's chromaloc group; 0 (the default) has each row
take its own pair's. With VIC_PATCH set, as the launcher
sets it, the fix (vic_patch.so) must be in the process and have patched VIC
jobs, none failed. Exactly one libcuda may be mapped.

--context picks the CUDA context the checks run in. primary (the default)
is the device's primary context, the one CUDA's runtime, TensorRT and
PyTorch use, current on this thread from before the pipeline starts. own is
a context of the program's own (cuCtxCreate), current the same way: on the
Nano (2026-10-17) it was found destroyed at the first copy after the
pipeline started (CUDA_ERROR_CONTEXT_IS_DESTROYED), with and without the
fix. pushed is a context of its own that is current only around the CUDA
calls (cuCtxPushCurrent and cuCtxPopCurrent), so that none is current while
GStreamer runs on this thread; late is one made only once the first frames
have arrived. CONTEXT_STATE lines give, once the pipeline has started, at
the first frames and once it has stopped, which context is current on this
thread (ours, the primary context, another or none, and whether another
works) and whether ours works there (pushed: once pushed).

Needs only Python's ctypes, GStreamer 1.x with its base plugins (appsink),
and the converter and CUDA driver in the library and plugin paths. Prints
KEY=VALUE lines, a FRAME line a frame, a LIB line for each NVIDIA library
the process mapped (the probe checks where each came from), and
VIC_CUDA=PASS or FAIL last (exit 0 or 1). Writes nothing; set
CUDA_CACHE_DISABLE=1 so the driver keeps no JIT cache.
"""
